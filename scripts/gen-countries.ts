// Generates assets/js/countries.js (ISO → Arabic/English name, region) from the ingest gazetteer.
// Usage: deno run -A scripts/gen-countries.ts
import { COUNTRIES } from "../supabase/functions/news-ingest/lib/geo.ts";
const SMALL = new Set(["of", "the", "and"]);
const OVERRIDE: Record<string, string> = { US: "United States", GB: "United Kingdom", AE: "UAE", CD: "DR Congo", CG: "Congo-Brazzaville", KR: "South Korea", KP: "North Korea", CI: "Côte d'Ivoire", GW: "Guinea-Bissau", TL: "Timor-Leste", BA: "Bosnia and Herzegovina", PS: "Palestine", VA: "Vatican", TD: "Chad", GE: "Georgia", CZ: "Czechia", SA: "Saudi Arabia", TR: "Türkiye", MM: "Myanmar", HK: "Hong Kong" };
const title = (s: string) => s.split(" ").map((w, i) => (i && SMALL.has(w) ? w : w[0].toUpperCase() + w.slice(1))).join(" ");
const AR_OVERRIDE: Record<string, string> = { ML: "مالي", BJ: "بنين", OM: "عُمان", JO: "الأردن", PS: "فلسطين", US: "الولايات المتحدة", GB: "بريطانيا", ID: "إندونيسيا" };
const rows = COUNTRIES.map((c) => `  ${c.iso}: [${JSON.stringify(AR_OVERRIDE[c.iso] ?? c.ar[0])}, ${JSON.stringify(OVERRIDE[c.iso] ?? title(c.en[0]))}, "${c.region}"],`);
const out = `// GENERATED by scripts/gen-countries.ts from the ingest gazetteer — do not edit by hand.
// ISO-3166 code → [Arabic name, English name, world region]
export const COUNTRIES = {
${rows.join("\n")}
};
`;
Deno.writeTextFileSync(new URL("../assets/js/countries.js", import.meta.url), out);
console.log(`${rows.length} countries`);
